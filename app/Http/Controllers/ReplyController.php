     * Store a newly created resource in storage.
     */
    public function store(Request $request)
    {
        $validated = $request->validate([
            'reply' => 'required|min:3|max:100',
            'commentId' => 'required|exists:comments,id',
        ], [], ['reply' => 'de resposta', 'commentId' => 'ID do comentário']);

        Reply::create([
            'user_id' => Auth::id(),
            'content' => $validated['reply'],
            'comment_id' => $validated['commentId'],
        ]);

        return response()->json('Resposta enviada com sucesso!', 200);
